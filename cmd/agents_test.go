// serverYAML is GET /agents/{name}/yaml's answer, byte for byte: the output of
// the control plane's serialize_agent_to_yaml (shared/config_parser.py at
// 8b1fb48) for a service agent on python3.11 with 1024 MB, a 5-minute idle
// timeout, always-on off and entrypoint main.py. Its first line is the
// yaml-language-server modeline, and it carries none of the platform's
// fields (name, description, workspace), which a deploy refuses.
const serverYAML = `# yaml-language-server: $schema=https://docs.aetherfy.com/aetherfy-yaml.schema.json
# aetherfy.yaml — exported from this agent's current configuration.
# Generated by Aetherfy (afy init --agent / dashboard Download YAML).
# Re-deploying this file applies the same configuration.
runtime: python3.11
type: service
memory_mb: 1024
idle_timeout_minutes: 5
keep_alive: false
entrypoint: main.py
`

// mockYAMLServer serves the agent YAML export at /agents/{name}/yaml.
func mockYAMLServer(t *testing.T) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasSuffix(r.URL.Path, "/agents/billing/yaml") {
			w.Header().Set("Content-Type", "application/yaml")
			w.WriteHeader(http.StatusOK)
			_, _ = w.Write([]byte(serverYAML))
			return
		}
		w.WriteHeader(http.StatusNotFound)
		_, _ = w.Write([]byte(`{"detail":{"code":"AGENT_NOT_FOUND","message":"not found"}}`))
	}))
}

// TestTheExportIsADeployableAetherfyYAML: the bytes from GetAgentYAML (what
// `afy init --agent` writes) parse as the aetherfy.yaml a deploy reads, open
// with the schema modeline, and carry neither server-derived fields nor the
// platform's.
func TestTheExportIsADeployableAetherfyYAML(t *testing.T) {
	srv := mockYAMLServer(t)
	defer srv.Close()
	client := api.NewClientWithURL(srv.URL, "afy_test_key")

	data, err := client.GetAgentYAML("billing")
	if err != nil {
		t.Fatalf("GetAgentYAML: %v", err)
	}

	var cfg archive.AetherfyConfig
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		t.Fatalf("the export does not parse: %v", err)
	}
	if cfg.Runtime != "python3.11" || cfg.MemoryMB != 1024 || cfg.Entrypoint != "main.py" {
		t.Errorf("round-trip lost fields: %+v", cfg)
	}
	if err := archive.CheckUnknownFields(data); err != nil {
		t.Errorf("the export names a key a deploy refuses: %v", err)
	}
	if !strings.HasPrefix(string(data), "# yaml-language-server: $schema=https://docs.aetherfy.com/aetherfy-yaml.schema.json\n") {
		t.Errorf("the export must open with the schema modeline:\n%s", data)
	}
	for _, leak := range []string{"status:", "fly_app_name:", "id:", "created_at", "name:", "workspace:", "description:"} {
		if strings.Contains(string(data), "\n"+leak) {
			t.Errorf("the export carries %q", leak)
		}
	}
}

